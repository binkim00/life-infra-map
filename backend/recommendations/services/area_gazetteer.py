# 사전에 적힌 이름 뒤에 흔히 붙는 표현입니다. `서면역`처럼 사전에 직접 넣은 별칭보다 뒤에 봅니다.
TRAILING_SUFFIXES = ("역", "동", "일대", "쪽", "근처", "주변", "인근")


def _normalize(value):
    return str(value or "").strip().replace(" ", "")


def resolve_area_coordinates(anchor_location):
    """
    지명이 사전에 있으면 `(위도, 경도, 표기명)`을, 없으면 None을 돌려준다.

    사전에 없는 지명은 기존대로 카카오 검색으로 넘어간다.
    """
    key = _normalize(anchor_location)
    if not key:
        return None

    if key in AREA_COORDINATES:
        lat, lng = AREA_COORDINATES[key]
        return lat, lng, key

    for suffix in TRAILING_SUFFIXES:
        if key.endswith(suffix) and len(key) > len(suffix):
            trimmed = key[: -len(suffix)]
            if trimmed in AREA_COORDINATES:
                lat, lng = AREA_COORDINATES[trimmed]
                return lat, lng, trimmed

    return None


def resolve_area_coordinates_by_token(anchor_location):
    """
    `서면 맛집거리`처럼 지명 뒤에 다른 말이 붙은 경우를 위해 낱말 단위로 한 번 더 찾는다.

    지명만 정확히 적힌 경우보다 정밀도가 떨어지므로,
    카카오 검색까지 실패했을 때만 마지막 수단으로 쓴다.
    """
    text = str(anchor_location or "").strip()
    if not text:
        return None

    tokens = [token for token in text.split() if token]
    # 긴 낱말을 먼저 봐서 `해운대해수욕장`이 `해운대`보다 우선 매칭되게 한다.
    for token in sorted(tokens, key=len, reverse=True):
        found = resolve_area_coordinates(token)
        if found:
            return found
    return None
